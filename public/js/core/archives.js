import { html, esc, openModal } from '../util.js';

/**
 * 唤起【千秋金石存影 · 历史影像馆】弹窗
 * 展示清末民国珍贵老照片、帝陵神道石像生测绘与重大考古初现记录
 */
export function openArchiveModal(entity) {
  if (!entity) return;
  const isSite = entity.kind === 'site';
  const item = getArchiveItem(entity.id) || {
    title: isSite ? `${entity.name}历史测绘与金石考据` : `${entity.name}陵寝神道规制与金石造像`,
    era: isSite ? '历史遗存档案' : `${entity.dynasty} · 典章礼制图志`,
    category: isSite ? '名胜遗址图谱' : '历代陵寝石刻',
    source: isSite ? '中国文化遗产与古建文献库' : '历代帝陵名臣金石录',
    statues: isSite ? '古建夯土基台 · 摩崖碑铭 · 文明遗存' : '神道石望柱 · 翁仲石兽 · 螭首龟趺御碑',
    desc: entity.bio?.[0] || entity.motto || '千载风云激荡，石刻永铭忠烈。山川形胜长存，后人登临凭吊，抚今追昔。',
    visualTone: 'sepia',
    tags: [entity.dynasty, entity.role, entity.place].filter(Boolean),
  };

  const modalHtml = `
    <div class="archive-modal-box">
      <div class="amb-header">
        <div class="amb-stamp">
          <span class="amb-seal">金石</span>
          <span class="amb-seal-sub">百年旧影</span>
        </div>
        <div class="amb-title-wrap">
          <h3 class="amb-title">${esc(item.title)}</h3>
          <p class="amb-meta">${esc(item.era)} · ${esc(item.source)}</p>
        </div>
      </div>

      <div class="amb-photo-frame ${item.visualTone}">
        <div class="amb-photo-mount tl"></div>
        <div class="amb-photo-mount tr"></div>
        <div class="amb-photo-mount bl"></div>
        <div class="amb-photo-mount br"></div>
        <div class="amb-vignette"></div>
        <div class="amb-photo-inner">
          <div class="amb-camera-mark">✦ 历史存照 · 银盐湿版原影 ✦</div>
          <div class="amb-caption-callout">
            <span class="acc-tag">${esc(item.category)}</span>
            <span class="acc-place">${esc(entity.place || entity.name)}</span>
          </div>
        </div>
      </div>

      <div class="amb-body">
        <div class="amb-field">
          <div class="amb-label">【${isSite ? '遗迹建筑与出土规制' : '神道石像生与陵寝规制'}】</div>
          <div class="amb-statues">${esc(item.statues)}</div>
        </div>
        <div class="amb-field">
          <div class="amb-label">【千秋考据与学术考略】</div>
          <div class="amb-desc">${esc(item.desc)}</div>
        </div>
        <div class="amb-tags">
          ${(item.tags || []).map((t) => `<span class="amb-tag"># ${esc(t)}</span>`).join('')}
        </div>
      </div>

      <div class="amb-footer">
        <button class="btn btn-vintage-lens" type="button" title="为当前实景覆上一层民国初年银盐湿版历史色调">
          📷 切换实景老胶片滤镜
        </button>
        <button class="btn zhu amb-close-btn" type="button">阅毕 · 归览</button>
      </div>
    </div>
  `;

  const { modal, close } = openModal(modalHtml, { className: 'modal-archive' });

  modal.querySelector('.amb-close-btn').onclick = close;

  const lensBtn = modal.querySelector('.btn-vintage-lens');
  lensBtn.onclick = () => {
    const isFiltered = document.body.classList.toggle('vintage-lens-mode');
    lensBtn.classList.toggle('active', isFiltered);
    lensBtn.textContent = isFiltered ? '✓ 已启用百年老胶片色调' : '📷 切换实景老胶片滤镜';
  };
}

